import test from 'node:test';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { mkdtemp, mkdir, writeFile, appendFile, rm } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
test('float feed watches ledger appends and pauses/resumes without a model call', async t => {
  const home = await mkdtemp(path.join(os.tmpdir(),'pulse-feed-'));
  assert.ok(path.resolve(home).startsWith(path.resolve(os.tmpdir())+path.sep));
  t.after(()=>rm(home,{recursive:true,force:true}));
  const id='01a13949-b780-71a2-8863-a7f53db88ead';
  const dir=path.join(home,'sessions',...new Date().toISOString().slice(0,10).split('-'));await mkdir(dir,{recursive:true});
  const file=path.join(dir,`rollout-${id}.jsonl`);
  const record=(seconds,total,out)=>JSON.stringify({timestamp:new Date(seconds*1000).toISOString(),type:'token_usage_record',payload:{thread_token_usage:{total_tokens:total,input_tokens:total-out,output_tokens:out}}})+'\n';
  await writeFile(file,record(0,100,10));
  const child=spawn(process.execPath,[fileURLToPath(new URL('../src/float-feed.mjs',import.meta.url)),'--thread',id],{env:{...process.env,CODEX_HOME:home,CODEX_PULSE_DISABLE_DESKTOP_EVENTS:'1',CODEX_PULSE_SETTINGS_FILE:path.join(home,'pulse-settings.json')},windowsHide:true});
  t.after(()=>child.kill());
  let buffer='',latest,received=0;
  child.stdout.on('data',chunk=>{buffer+=chunk;let end;while((end=buffer.indexOf('\n'))>=0){latest=JSON.parse(buffer.slice(0,end));received++;buffer=buffer.slice(end+1);}});
  const waitFor=async predicate=>{const deadline=Date.now()+3000;while(!predicate()){assert.ok(Date.now()<deadline,'feed event timed out');await new Promise(resolve=>setTimeout(resolve,20));}};
  await waitFor(()=>latest?.usage?.total_tokens===100);
  const began=performance.now();await appendFile(file,record(10,200,40));await waitFor(()=>latest?.usage?.total_tokens===200);
  t.diagnostic(`append to stdout: ${Math.round(performance.now()-began)}ms (test fixture)`);
  child.stdin.write('pause\n');await new Promise(resolve=>setTimeout(resolve,150));const before=received;
  await appendFile(file,record(20,300,80));await new Promise(resolve=>setTimeout(resolve,650));
  assert.equal(received,before,'explicitly paused feed must stop producing samples');
  child.stdin.write('resume\n');await waitFor(()=>latest?.usage?.total_tokens===300);assert.equal(latest.latestRate,4);
  assert.equal(latest.reportedPoints.at(-1).rate,4,'TPS series retains reported output token delta per second');
  child.stdin.write('pause\n');await new Promise(resolve=>setTimeout(resolve,100));
  const exit=new Promise(resolve=>child.once('exit',resolve));child.stdin.end();
  const stopped=await Promise.race([exit.then(()=>true),new Promise(resolve=>{const timer=setTimeout(()=>resolve(false),3000);timer.unref();})]);
  assert.equal(stopped,true,'paused collector must stop when its parent closes stdin');assert.equal(child.exitCode,0);
});
